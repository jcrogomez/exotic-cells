"""Writes the full-stage decks: V2 bias chain (bottom = 16 x DUT) + precharge pfet + DUT + library inverter.

stage_K<k>_<vdd mV>_<T>.sp  transient: release at 100 ns, time to the inverter output crossing VDD/2
                            for the DUT, the DUT with +0.305 mV on the gate, and the 4.2/1.5 twin.
noise_K<k>.sp               output noise of the bias node with 1 pF.
leak_<T>.sp                 off-state current of the precharge pfet.
"""
N, Pm = "sky130_fd_pr__nfet_01v8", "sky130_fd_pr__pfet_01v8"
HEAD = [".lib /pdk/libs.tech/ngspice/sky130.lib.spice tt",
        ".include /pdk/libs.ref/sky130_fd_sc_hd/spice/sky130_fd_sc_hd.spice",
        ".options gmin=1e-18 abstol=1e-18 reltol=1e-5"]

def chain(K, sup="vdd"):
    nodes = [sup] + [f"c{i}" for i in range(1, K - 1)] + ["vb", "0"]
    L = []
    for i in range(K):
        geo = "w=0.42 l=0.15 m=16" if i == K - 1 else "w=1 l=1"
        L.append(f"Xc{i} {nodes[i]} {nodes[i]} {nodes[i+1]} 0 {N} {geo}")
    return L + ["Cf vb 0 1p"]

def stage(tag, gate, geo, pre=Pm + " w=0.42 l=0.15"):
    return [f"Xp{tag} x{tag} pre vdd vdd {pre}",
            f"Xd{tag} x{tag} {gate} 0 0 {N} {geo}",
            f"Xi{tag} x{tag} 0 0 vdd vdd y{tag} sky130_fd_sc_hd__inv_1"]

for K, tstop, tstep in ((3, "5u", "0.2n"), (4, "200u", "10n")):
    for vdd in (1.80, 1.81):
        for T in (27,):
            L = [f"* XC-19 full stage, K = {K}, VDD = {vdd}, {T} C. Generated by gen_stage.py"] + HEAD + [f".temp {T}",
                 f"Vdd vdd 0 {vdd}", f"Vpre pre 0 pulse(0 {vdd} 100n 1n 1n 1 2)", "Vstep vbs vb 0.305m"]
            L += chain(K) + stage("a", "vb", "w=0.42 l=0.15") + stage("b", "vbs", "w=0.42 l=0.15") + stage("w", "vb", "w=4.2 l=1.5")
            L += [".control", f"tran {tstep} {tstop}",
                  f"meas tran ta when v(ya)={vdd/2} rise=1", f"meas tran tb when v(yb)={vdd/2} rise=1",
                  f"meas tran tw when v(yw)={vdd/2} rise=1",
                  f"meas tran xa find v(xa) when v(ya)={vdd/2} rise=1",
                  "let vb0 = v(vb)[0]", "meas tran vbmin min v(vb)", "meas tran vbmax max v(vb)",
                  f"echo STAGE {K} {vdd} {T} $&ta $&tb $&tw $&xa $&vb0 $&vbmin $&vbmax", "quit", ".endc", ".end"]
            open(f"stage_K{K}_{int(vdd*1000)}_{T}.sp", "w").write("\n".join(L) + "\n")
    L = [f"* XC-19 bias noise, K = {K}"] + HEAD + [".temp 27", "Vdd vdd 0 1.8 ac 1"] + chain(K)
    L += [".control", "noise v(vb) Vdd dec 20 1 1e6", "setplot noise2", "let vn = onoise_total",
          f"echo NOISE {K} total_Vrms $&vn", "setplot noise1",
          "let s1 = onoise_spectrum[0]", "let s2 = onoise_spectrum[60]", "let s3 = onoise_spectrum[100]",
          f"echo NOISE {K} spectrum_V_per_rtHz_at_1Hz_1kHz_100kHz $&s1 $&s2 $&s3", "quit", ".endc", ".end"]
    open(f"noise_K{K}.sp", "w").write("\n".join(L) + "\n")
for T in (27, 85):
    L = [f"* precharge pfet off-state current, {T} C"] + HEAD + [f".temp {T}", "Vdd vdd 0 1.8", "Vx x 0 0.9",
         f"Xp x vdd vdd vdd {Pm} w=0.42 l=0.15", ".control", "op", "let il = i(Vx)", f"echo LEAK {T} $&il", "quit", ".endc", ".end"]
    open(f"leak_{T}.sp", "w").write("\n".join(L) + "\n")
