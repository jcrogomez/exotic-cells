"""Writes bias_<corner>_<T>.sp: diode-chain bias, variants V1 (all 1/1 um) and V2 (bottom = 16 x DUT), K = 3..8."""
N = "sky130_fd_pr__nfet_01v8"
for corner in ("tt", "ss", "ff", "sf", "fs"):
    for T in (27, 85):
        L = [f"* XC-19 bias chain. corner {corner}, {T} C. Generated by gen_bias.py",
             f".lib /pdk/libs.tech/ngspice/sky130.lib.spice {corner}", f".temp {T}",
             "Vdd vdd 0 1.8", "Vdd2 vdd2 0 1.81", ".options gmin=1e-18 abstol=1e-18 reltol=1e-6"]
        ctl = [".control", "op"]
        for var in ("v1", "v2"):
            for K in range(3, 9):
                for sup in ("vdd", "vdd2"):
                    t = f"{var}k{K}{'' if sup == 'vdd' else 'h'}"
                    nodes = [sup] + [f"{t}n{i}" for i in range(1, K)] + ["0"]
                    for i in range(K):
                        top, bot = nodes[i], nodes[i + 1]
                        if i == K - 1 and var == "v2":
                            L.append(f"X{t}m{i} {top} {top} {bot} 0 {N} w=0.42 l=0.15 m=16")
                        else:
                            L.append(f"X{t}m{i} {top} {top} {bot} 0 {N} w=1 l=1")
                    vb = nodes[K - 1]
                    L += [f"Vd{t} d{t} 0 0.9", f"Xdut{t} d{t} {vb} 0 0 {N} w=0.42 l=0.15"]
                    ctl += [f"let vb = v({vb})", f"let idut = -i(Vd{t})",
                            f"echo BIAS {corner} {T} {var} {K} {sup} $&vb $&idut"]
        L += ctl + ["quit", ".endc", ".end"]
        open(f"bias_{corner}_{T}.sp", "w").write("\n".join(L) + "\n")
