"""Seat-matrix generator: a table of devices in, a Magic layout, an LVS reference and a seat list out.

Each seat is one nfet (1.8 V) under test with a source switch (nfet 0.84/0.15) below it, the pair used by the XC-19 reader
(cells/xc19_slot_core_a2/xc19_slot_core.tcl, cell xc19_read_s). All drains join the reader node X, all gates the bias VB, all
switch sources GND; each switch gate is its own pin SEL<k>.

    y (um)   layer     what
     W+0.30  metal 1   X bus
     0..W    diff      device under test (gate pad below it, on VB)
    -0.66    metal 1   VB bus
    -1.74    metal 1   GND bus, over the switches' sources and the substrate taps
    -1.96    diff      source switch
    -2.62    poly      switch gate pad -> via stack -> metal 2 pin SEL<k>, running down to y = -3.20

Table (JSON): {"name": ..., "tap_every": 8, "tap_max": 10.0, "seats": [{"id": "C0", "w": 0.42, "l": 0.15, "sa": 0.30, "sb": 0.30, "n": 1}, ...]}
"n" repeats a seat. Per-seat options (XC-19 fan): "bone": 0.42 widens the drain diffusion 0.075 um after the gate; "dummy": true adds
unconnected poly strips on both sides; "butt": true puts a p+ block against the source end. Limits: one row, nfet only, w >= 0.42, sa and sb >= 0.30 (a contact fits between gate and diffusion end).

Usage: matrix.py <table.json> <out_dir> [--pitch-delta D]     (D shrinks the seat pitch; used only to prove the DRC looks)
Writes <name>.tcl, <name>_ref.spice, <name>_seats.csv. Run the .tcl in Magic with the sky130A rc file (see run.sh).
"""
import json, os, sys

GAP = 0.27          # diffusion to diffusion, diffusion to tap
SW_W, SW_L = 0.84, 0.15
TAP = 0.42
BUTT = 0.42         # p+ block touching the source end of a seat ("butt": true)
DUMMY = 0.15        # width of the unconnected poly strips beside a seat ("dummy": true); "dummy_gap" in the table sets their distance to the diffusion


def q(v):
    return f"{round(v / 0.005) * 0.005:.3f}"


class Tcl:
    def __init__(self): self.l = []
    def r(self, layer, x0, y0, x1, y1): self.l.append(f"r {layer} {q(x0)} {q(y0)} {q(x1)} {q(y1)}")
    def pin(self, name, layer, x0, y0, x1, y1): self.l.append(f"pin {name} {layer} {q(x0)} {q(y0)} {q(x1)} {q(y1)}")


def expand(table):
    seats = []
    for s in table["seats"]:
        for k in range(int(s.get("n", 1))):
            d = dict(w=float(s["w"]), l=float(s["l"]), sa=float(s.get("sa", 0.30)), sb=float(s.get("sb", 0.30)))
            assert d["w"] >= 0.42 and d["l"] >= 0.15 and d["sa"] >= 0.30 and d["sb"] >= 0.30, s
            d["id"] = s["id"] if int(s.get("n", 1)) == 1 else f"{s['id']}_{k}"
            d["bone"] = float(s.get("bone", 0.0)); d["dummy"] = bool(s.get("dummy", False)); d["butt"] = bool(s.get("butt", False))
            assert not (d["dummy"] and d["butt"]), s
            seats.append(d)
    return seats


def frame(name):
    head = ["# SPDX-License-Identifier: Apache-2.0", f"# Generated by generator/matrix.py from table '{name}'. Do not edit by hand.",
            "proc r {layer x0 y0 x1 y1} { box ${x0}um ${y0}um ${x1}um ${y1}um ; paint $layer }",
            "proc pin {name layer x0 y0 x1 y1} { box ${x0}um ${y0}um ${x1}um ${y1}um ; label $name FreeSans 20 0 0 0 c $layer ; port make }",
            "drc off", f"cellname create {name} ; load {name}"]
    tail = ["box -500um -500um 500um 500um", "drc style drc(full)", "drc on ; drc check ; drc catchup", "set rules {}",
            'foreach {msg boxes} [drc listall why] { lappend rules "$msg  @ [lrange $boxes 0 3]" }',
            f'puts "DRC {name} violations=[llength $rules]"', 'foreach x $rules { puts "   $x" }', "drc off",
            f"save {name}", f"gds write {name}.gds", "extract all", "ext2spice lvs", f"ext2spice -o {name}.lvs.spice",
            "ext2spice cthresh 0", "ext2spice rthresh infinite", f"ext2spice -o {name}.pex.spice",
            'select top cell ; puts "BBOX [box values]"', "quit -noprompt"]
    return head, tail


def build(table, pitch_delta=0.0):
    name = table["name"]; seats = expand(table); every = int(table.get("tap_every", 8)); tap_max = float(table.get("tap_max", 10.0))
    wmax = max(s["w"] + s["bone"] for s in seats); dg = float(table.get("dummy_gap", 0.075))
    yx0 = wmax + 0.30; yx1 = yx0 + 0.37                     # X bus
    t = Tcl(); x = 0.0; rows = []

    def tap(x):
        t.r("psubdiff", x, -1.75, x + TAP, -1.33)
        t.r("psubdiffcont", x + 0.125, -1.69, x + 0.295, -1.39)
        t.r("locali", x + 0.125, -1.77, x + 0.295, -1.31)
        t.r("viali", x + 0.125, -1.625, x + 0.295, -1.455)
        return x + TAP + GAP

    x = tap(x); last_tap = x - GAP; last_k = 0
    for k, s in enumerate(seats):
        w, l, sa, sb = s["w"], s["l"], s["sa"], s["sb"]; xe = sa + l + sb; ws = max(xe, 0.75, sa + max(l, 0.34))
        # a substrate tap by count, or when this seat's diffusion would end farther than tap_max from the last tap (rule LU.2: 15 um)
        pre = (BUTT if s["butt"] else 0.0) + (DUMMY + dg if s["dummy"] else 0.0); post = DUMMY + dg if s["dummy"] else 0.0
        if k and (k - last_k >= every or x + pre + ws + post - last_tap > tap_max): x = tap(x); last_tap = x - GAP; last_k = k
        x += pre
        X = lambda v: x + v
        if s["bone"]: t.r("ndiff", X(sa + l + 0.075), 0, X(xe), w + s["bone"])     # STI corner 0.075 um from the gate, drain side
        if s["butt"]:                                                              # p+ touching the source end; its own contact (licon.16), tied to nothing: it is substrate
            t.r("psubdiff", X(-BUTT), 0, X(0), w); t.r("psubdiffcont", X(-0.30), 0.06, X(-0.13), w - 0.06); t.r("locali", X(-0.30), -0.02, X(-0.13), w + 0.02)
        if s["dummy"]:                                                             # unconnected poly strips on the field, both sides
            t.r("poly", X(-dg - DUMMY), -0.13, X(-dg), w + 0.13); t.r("poly", X(xe + dg), -0.13, X(xe + dg + DUMMY), w + 0.13)
        # device under test
        t.r("ndiff", X(0), 0, X(xe), w)
        t.r("poly", X(sa), -0.29, X(sa + l), w + 0.13)
        t.r("ndiffc", X(0.04), 0.06, X(0.21), w - 0.06)
        t.r("ndiffc", X(xe - 0.21), 0.06, X(xe - 0.04), w - 0.06)
        t.r("poly", X(sa), -0.62, X(sa + max(l, 0.34)), -0.29)
        t.r("polycont", X(sa + 0.09), -0.54, X(sa + 0.26), -0.37)
        t.r("locali", X(sa + 0.09), -0.62, X(sa + 0.26), -0.29)
        t.r("viali", X(sa + 0.09), -0.60, X(sa + 0.26), -0.43)                      # gate -> VB bus
        # source strap down to the switch drain; drain strap up to the X bus
        t.r("locali", X(0.04), -1.98, X(0.21), w + 0.02)
        t.r("locali", X(xe - 0.21), -0.02, X(xe - 0.04), yx0 + 0.33)
        t.r("viali", X(xe - 0.21), yx0 + 0.10, X(xe - 0.04), yx0 + 0.27)
        # source switch
        t.r("ndiff", X(0), -1.96, X(0.75), -1.12)
        t.r("poly", X(0.30), -2.09, X(0.45), -0.99)
        t.r("ndiffc", X(0.04), -1.90, X(0.21), -1.18)
        t.r("ndiffc", X(0.54), -1.90, X(0.71), -1.18)
        t.r("locali", X(0.54), -1.98, X(0.71), -1.10)
        t.r("viali", X(0.54), -1.625, X(0.71), -1.455)                              # source -> GND bus
        t.r("poly", X(0.30), -2.62, X(0.64), -2.09)
        t.r("polycont", X(0.39), -2.54, X(0.56), -2.37)
        t.r("locali", X(0.39), -2.62, X(0.56), -2.29)
        t.r("viali", X(0.39), -2.54, X(0.56), -2.37)
        cx, cy = X(0.475), -2.455
        t.r("metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20)
        t.r("via1", cx - 0.13, cy - 0.13, cx + 0.13, cy + 0.13)
        t.r("metal2", cx - 0.18, -3.20, cx + 0.18, cy + 0.18)
        t.pin(f"SEL{k}", "metal2", cx - 0.18, -3.20, cx + 0.18, -2.90)
        opt = "bone" if s["bone"] else "dummy" if s["dummy"] else "butt" if s["butt"] else ""
        rows.append(dict(seat=k, id=s["id"], x=round(x, 3), w=w, l=l, sa=sa, sb=sb, sel=f"SEL{k}", opt=opt))
        x += ws + post + GAP + pitch_delta
    x = tap(x) - GAP
    for y0, y1, n in ((yx0, yx1, "X"), (-0.66, -0.37, "VB"), (-1.74, -1.34, "GND")):
        t.r("metal1", 0, y0, x, y1); t.pin(n, "metal1", 0, y0, 0.40, y1)
    head, tail = frame(name)
    ref = [f"* Reference for LVS, generated from table '{name}'. Do not edit by hand.",
           f".subckt {name} X VB GND " + " ".join(r["sel"] for r in rows)]
    for r in rows:
        k = r["seat"]
        ref.append(f"XD{k} X VB s{k} GND sky130_fd_pr__nfet_01v8 w={r['w']:g} l={r['l']:g}")
        ref.append(f"XS{k} s{k} SEL{k} GND GND sky130_fd_pr__nfet_01v8 w={SW_W:g} l={SW_L:g}")
    ref.append(".ends")
    csv = ["seat,id,x_um,w_um,l_um,sa_um,sb_um,select,option"] + [f"{r['seat']},{r['id']},{r['x']},{r['w']},{r['l']},{r['sa']},{r['sb']},{r['sel']},{r['opt']}" for r in rows]
    return name, "\n".join(head + t.l + tail) + "\n", "\n".join(ref) + "\n", "\n".join(csv) + "\n"


JGAP = 1.50         # between the p+ of one seat and the n+ of the next: no unintended pair closer than the widest gap tested
WDIODE = "pdiode"   # the same for the p+ island of the n-well variant; "pdiff" draws it as plain diffusion
WENC = 0.18         # n-well enclosure of the p+ island and of the n+ tap
DIODE = "ndiode"    # paint the n+ island as a diode so extraction yields a device; "ndiff" draws it as plain diffusion


def build_junction(table, pitch_delta=0.0):
    """XC-20, substrate variant: an n+ island (1.0 x 1.4 um by default) with a p+ substrate tap at distance d, boundary along
    y. A series switch (nfet 0.84/0.15) joins the island to the reader node X; the p+ tap is GND. d = null: no junction (the
    tap is 3 um away). Seats: {"id": ..., "d": 0.0, "w": 1.0, "h": 1.4, "n": 1}"""
    name = table["name"]; seats = []
    for s in table["seats"]:
        for k in range(int(s.get("n", 1))):
            seats.append(dict(id=s["id"] if int(s.get("n", 1)) == 1 else f"{s['id']}_{k}", d=s.get("d"), w=float(s.get("w", 1.0)), h=float(s.get("h", 1.4))))
    hmax = max(s["h"] for s in seats); yx0 = hmax + 0.30; yx1 = yx0 + 0.37
    cont = DIODE + "c" if DIODE != "ndiff" else "ndiffc"
    t = Tcl(); x = 0.0; rows = []; xmax = 0.0
    for k, s in enumerate(seats):
        d = 3.0 if s["d"] is None else float(s["d"]); w, h = s["w"], s["h"]; X = lambda v: x + v
        t.r(DIODE, X(0), 0, X(w), h)                                               # n+ island
        t.r(cont, X(0.04), 0.06, X(0.21), h - 0.06)
        t.r("locali", X(0.04), -1.98, X(0.21), h + 0.02)                           # island -> switch source
        px = w + d                                                                 # p+ tap, GND
        t.r("psubdiff", X(px), 0, X(px + 1.0), h)
        t.r("psubdiffcont", X(px + 0.415), 0.06, X(px + 0.585), h - 0.06)
        t.r("locali", X(px + 0.415), -0.97, X(px + 0.585), h + 0.02)
        t.r("viali", X(px + 0.415), -0.86, X(px + 0.585), -0.69)
        t.r("ndiff", X(0), -1.96, X(0.75), -1.12)                                  # series switch
        t.r("poly", X(0.30), -2.09, X(0.45), -0.99)
        t.r("ndiffc", X(0.04), -1.90, X(0.21), -1.18)
        t.r("ndiffc", X(0.54), -1.90, X(0.71), -1.18)
        t.r("locali", X(0.54), -1.98, X(0.71), yx0 + 0.33)                         # switch drain -> X bus
        t.r("viali", X(0.54), yx0 + 0.10, X(0.71), yx0 + 0.27)
        t.r("poly", X(0.30), -2.62, X(0.64), -2.09)
        t.r("polycont", X(0.39), -2.54, X(0.56), -2.37)
        t.r("locali", X(0.39), -2.62, X(0.56), -2.29)
        t.r("viali", X(0.39), -2.54, X(0.56), -2.37)
        cx, cy = X(0.475), -2.455
        t.r("metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20)
        t.r("via1", cx - 0.13, cy - 0.13, cx + 0.13, cy + 0.13)
        t.r("metal2", cx - 0.18, -3.20, cx + 0.18, cy + 0.18)
        t.pin(f"SEL{k}", "metal2", cx - 0.18, -3.20, cx + 0.18, -2.90)
        rows.append(dict(seat=k, id=s["id"], x=round(x, 3), d=s["d"], w=w, h=h, sel=f"SEL{k}"))
        xmax = x + px + 1.0; x = xmax + JGAP + pitch_delta
    for y0, y1, n in ((yx0, yx1, "X"), (-0.95, -0.60, "GND")):
        t.r("metal1", 0, y0, xmax, y1); t.pin(n, "metal1", 0, y0, 0.40, y1)
    head, tail = frame(name)
    ref = [f"* Reference for LVS, generated from table '{name}'. Do not edit by hand.", f".subckt {name} X GND " + " ".join(r["sel"] for r in rows)]
    for r in rows:
        k = r["seat"]
        if DIODE != "ndiff": ref.append(f"XJ{k} GND n{k} sky130_fd_pr__diode_pw2nd_05v5 area={r['w'] * r['h'] * 1e12:g} perim={2 * (r['w'] + r['h']) * 1e6:g}")
        ref.append(f"XS{k} X SEL{k} n{k} GND sky130_fd_pr__nfet_01v8 w={SW_W:g} l={SW_L:g}")
    ref.append(".ends")
    csv = ["seat,id,x_um,d_um,w_um,h_um,select"] + [f"{r['seat']},{r['id']},{r['x']},{'' if r['d'] is None else r['d']},{r['w']},{r['h']},{r['sel']}" for r in rows]
    return name, "\n".join(head + t.l + tail) + "\n", "\n".join(ref) + "\n", "\n".join(csv) + "\n"


def build_wjunction(table, pitch_delta=0.0):
    """XC-20, n-well variant (main one since MISFIT-15): a p+ island (1.0 x 1.4 um by default) painted as a diode inside one
    shared n-well, with an n+ well tap at distance d. The well taps go to the reader node X; a switch (nfet 0.84/0.15) outside
    the well joins the island to GND, so the junction sees the node voltage. One p+ substrate tap per seat next to the switch.
    d = null: no junction (the tap is 3 um away). Seats: {"id": ..., "d": 0.0, "w": 1.0, "h": 1.4, "n": 1}"""
    name = table["name"]; seats = []
    for s in table["seats"]:
        for k in range(int(s.get("n", 1))):
            seats.append(dict(id=s["id"] if int(s.get("n", 1)) == 1 else f"{s['id']}_{k}", d=s.get("d"), w=float(s.get("w", 1.0)), h=float(s.get("h", 1.4))))
    hmax = max(s["h"] for s in seats); yx0 = hmax + 0.30; yx1 = yx0 + 0.37
    t = Tcl(); x = 0.0; rows = []; xmax = 0.0
    for k, s in enumerate(seats):
        d = 3.0 if s["d"] is None else float(s["d"]); w, h = s["w"], s["h"]; X = lambda v: x + v
        t.r(WDIODE, X(0), 0, X(w), h)                                              # p+ island, in the well
        t.r(WDIODE + "c" if WDIODE != "pdiff" else "pdiffc", X(0.04), 0.06, X(0.21), h - 0.06)
        t.r("locali", X(0.04), -1.98, X(0.21), h + 0.02)                           # island -> switch drain
        px = w + d                                                                 # n+ well tap, on X
        t.r("nsubdiff", X(px), 0, X(px + 1.0), h)
        t.r("nsubdiffcont", X(px + 0.415), 0.06, X(px + 0.585), h - 0.06)
        t.r("locali", X(px + 0.415), -0.02, X(px + 0.585), yx0 + 0.33)
        t.r("viali", X(px + 0.415), yx0 + 0.10, X(px + 0.585), yx0 + 0.27)
        t.r("ndiff", X(0), -1.96, X(0.75), -1.12)                                  # switch, outside the well
        t.r("poly", X(0.30), -2.09, X(0.45), -0.99)
        t.r("ndiffc", X(0.04), -1.90, X(0.21), -1.18)
        t.r("ndiffc", X(0.54), -1.90, X(0.71), -1.18)
        t.r("locali", X(0.54), -1.98, X(0.71), -0.60)                              # switch source -> GND bus
        t.r("viali", X(0.54), -0.86, X(0.71), -0.69)
        t.r("psubdiff", X(1.20), -1.96, X(1.62), -1.12)                            # substrate tap -> GND bus
        t.r("psubdiffcont", X(1.325), -1.90, X(1.495), -1.18)
        t.r("locali", X(1.325), -1.98, X(1.495), -0.60)
        t.r("viali", X(1.325), -0.86, X(1.495), -0.69)
        t.r("poly", X(0.30), -2.62, X(0.64), -2.09)
        t.r("polycont", X(0.39), -2.54, X(0.56), -2.37)
        t.r("locali", X(0.39), -2.62, X(0.56), -2.29)
        t.r("viali", X(0.39), -2.54, X(0.56), -2.37)
        cx, cy = X(0.475), -2.455
        t.r("metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20)
        t.r("via1", cx - 0.13, cy - 0.13, cx + 0.13, cy + 0.13)
        t.r("metal2", cx - 0.18, -3.20, cx + 0.18, cy + 0.18)
        t.pin(f"SEL{k}", "metal2", cx - 0.18, -3.20, cx + 0.18, -2.90)
        rows.append(dict(seat=k, id=s["id"], x=round(x, 3), d=s["d"], w=w, h=h, sel=f"SEL{k}"))
        xmax = x + px + 1.0; x = xmax + JGAP + pitch_delta
    t.r("nwell", -WENC, -WENC, xmax + WENC, hmax + WENC)                           # one well for the whole table, on X
    for y0, y1, n in ((yx0, yx1, "X"), (-0.95, -0.60, "GND")):
        t.r("metal1", 0, y0, xmax, y1); t.pin(n, "metal1", 0, y0, 0.40, y1)
    head, tail = frame(name)
    ref = [f"* Reference for LVS, generated from table '{name}'. Do not edit by hand.",
           f"* n-well drawn: {xmax + 2 * WENC:.3f} x {hmax + 2 * WENC:.3f} um", f".subckt {name} X GND " + " ".join(r["sel"] for r in rows)]
    for r in rows:
        k = r["seat"]
        if WDIODE != "pdiff": ref.append(f"XJ{k} n{k} X sky130_fd_pr__diode_pd2nw_05v5 area={r['w'] * r['h'] * 1e12:g} perim={2 * (r['w'] + r['h']) * 1e6:g}")
        ref.append(f"XS{k} n{k} SEL{k} GND GND sky130_fd_pr__nfet_01v8 w={SW_W:g} l={SW_L:g}")
    ref.append(".ends")
    csv = ["seat,id,x_um,d_um,w_um,h_um,select"] + [f"{r['seat']},{r['id']},{r['x']},{'' if r['d'] is None else r['d']},{r['w']},{r['h']},{r['sel']}" for r in rows]
    return name, "\n".join(head + t.l + tail) + "\n", "\n".join(ref) + "\n", "\n".join(csv) + "\n"


GAP_MV = 0.32       # between thick-oxide diffusions (0.30 by rule)
OX = {"thick": dict(diff="mvndiff", cont="mvndiffc", w=0.42, l=0.50, model="sky130_fd_pr__nfet_g5v0d10v5"),
      "thin": dict(diff="ndiff", cont="ndiffc", w=0.42, l=0.15, model="sky130_fd_pr__nfet_01v8")}


def build_fgate(table, pitch_delta=0.0):
    """XC-14: a read transistor between the reader node X and a source switch, whose gate goes nowhere but up, in poly, to a
    metal 1 plate (the antenna). A metal 2 strip, CP, runs over all plates: the common coupling plate. Per seat: "ox" ("thick":
    nfet_g5v0d10v5 0.42/0.5, "thin": nfet_01v8 0.42/0.15), "ant_w" x "ant_h" (plate, um), "diode": true (a small n+ diode on the
    gate, in local interconnect: the twin with a discharge path), "tied": true (the gate also goes to the VB bus).
    Table options: "shield" (default true: a grounded metal 1 strip between the X bus and the plates), "cp_split" (default true: the
    coupling plate is two interleaved combs, CP1 and CP2, instead of one strip CP)."""
    name = table["name"]; seats = []; pg = float(table.get("plate_gap", 0.30)); hints = []   # wide metal 1 wants 0.28 um
    for s in table["seats"]:
        for k in range(int(s.get("n", 1))):
            seats.append(dict(id=s["id"] if int(s.get("n", 1)) == 1 else f"{s['id']}_{k}", ox=s.get("ox", "thick"), aw=float(s.get("ant_w", 0.80)),
                              ah=float(s.get("ant_h", 0.45)), diode=bool(s.get("diode", False)), tied=bool(s.get("tied", False))))
    shield = bool(table.get("shield", True)); split = bool(table.get("cp_split", True))
    sa = sb = 0.30; yx0 = 0.42 + 0.30; yx1 = yx0 + 0.37; yp = yx1 + (0.61 if shield else 0.35); tap_max = float(table.get("tap_max", 10.0))
    t = Tcl(); x = 0.0; rows = []

    def tap(x):
        t.r("psubdiff", x, -1.75, x + TAP, -1.33)
        t.r("psubdiffcont", x + 0.125, -1.69, x + 0.295, -1.39)
        t.r("locali", x + 0.125, -1.77, x + 0.295, -1.31)
        t.r("viali", x + 0.125, -1.625, x + 0.295, -1.455)
        return x + TAP + GAP

    x = tap(x); last_tap = x - GAP; xend = x
    for k, s in enumerate(seats):
        o = OX[s["ox"]]; w, l = o["w"], o["l"]; xe = sa + l + sb; gx = sa + l / 2; da = sa + l + 0.30
        assert s["aw"] >= max(0.80, gx + 0.20) and s["ah"] >= 0.45 and (not s["diode"] or s["aw"] >= da + 0.45), s
        ws = max(xe, 0.75)
        if k and x + ws - last_tap > tap_max: x = tap(x); last_tap = x - GAP
        X = lambda v: x + v
        if s["ox"] == "thick":                                                      # thick oxide over the whole gate poly run (hvpoly.14)
            hints += [X(sa - 0.10), -0.72 if s["tied"] else -0.18, X(sa + l + 0.10), yp + 0.45]
        t.r(o["diff"], X(0), 0, X(xe), w)                                           # read transistor
        t.r("poly", X(sa), -0.29 if s["tied"] else -0.13, X(sa + l), yp + 0.35)     # its gate, running up under the X bus to the plate
        t.r(o["cont"], X(0.04), 0.06, X(0.21), w - 0.06)
        t.r(o["cont"], X(xe - 0.21), 0.06, X(xe - 0.04), w - 0.06)
        if s["tied"]:                                                               # twin: the gate also on the VB bus
            t.r("poly", X(sa), -0.62, X(sa + max(l, 0.34)), -0.29)
            t.r("polycont", X(sa + 0.09), -0.54, X(sa + 0.26), -0.37)
            t.r("locali", X(sa + 0.09), -0.62, X(sa + 0.26), -0.29)
            t.r("viali", X(sa + 0.09), -0.60, X(sa + 0.26), -0.43)
        t.r("locali", X(0.04), -1.98, X(0.21), w + 0.02)                            # source -> switch drain
        t.r("locali", X(xe - 0.21), -0.02, X(xe - 0.04), yx0 + 0.33)                # drain -> X bus
        t.r("viali", X(xe - 0.21), yx0 + 0.10, X(xe - 0.04), yx0 + 0.27)
        t.r("poly", X(gx - 0.17), yp + 0.02, X(gx + 0.17), yp + 0.35)               # gate pad -> metal 1 plate
        t.r("polycont", X(gx - 0.085), yp + 0.10, X(gx + 0.085), yp + 0.27)
        t.r("locali", X(gx - 0.085), yp + 0.02, X(gx + 0.085), yp + 0.35)
        t.r("viali", X(gx - 0.085), yp + 0.10, X(gx + 0.085), yp + 0.27)
        t.r("metal1", X(0), yp - 0.05, X(s["aw"]), yp - 0.05 + s["ah"])             # the antenna
        if s["diode"]:
            t.r("ndiode", X(da), yp - 0.04, X(da + 0.45), yp + 0.41)
            t.r("ndiodec", X(da + 0.14), yp + 0.10, X(da + 0.31), yp + 0.27)
            t.r("locali", X(gx - 0.085), yp + 0.10, X(da + 0.39), yp + 0.27)
        t.r("ndiff", X(0), -1.96, X(0.75), -1.12)                                   # source switch, as in build()
        t.r("poly", X(0.30), -2.09, X(0.45), -0.99)
        t.r("ndiffc", X(0.04), -1.90, X(0.21), -1.18)
        t.r("ndiffc", X(0.54), -1.90, X(0.71), -1.18)
        t.r("locali", X(0.54), -1.98, X(0.71), -1.10)
        t.r("viali", X(0.54), -1.625, X(0.71), -1.455)
        t.r("poly", X(0.30), -2.62, X(0.64), -2.09)
        t.r("polycont", X(0.39), -2.54, X(0.56), -2.37)
        t.r("locali", X(0.39), -2.62, X(0.56), -2.29)
        t.r("viali", X(0.39), -2.54, X(0.56), -2.37)
        cx, cy = X(0.475), -2.455
        t.r("metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20)
        t.r("via1", cx - 0.13, cy - 0.13, cx + 0.13, cy + 0.13)
        t.r("metal2", cx - 0.18, -3.20, cx + 0.18, cy + 0.18)
        t.pin(f"SEL{k}", "metal2", cx - 0.18, -3.20, cx + 0.18, -2.90)
        rows.append(dict(seat=k, id=s["id"], x=round(x, 3), ox=s["ox"], aw=s["aw"], ah=s["ah"], sel=f"SEL{k}", w=w, l=l, model=o["model"],
                         opt="diode" if s["diode"] else "tied" if s["tied"] else ""))
        xend = x + max(ws, s["aw"]); x += max(ws + GAP_MV, s["aw"] + pg) + pitch_delta
    x = tap(max(x, xend + GAP)) - GAP
    for y0, y1, n in ((yx0, yx1, "X"), (-0.66, -0.37, "VB"), (-1.74, -1.34, "GND")):
        t.r("metal1", 0, y0, x, y1); t.pin(n, "metal1", 0, y0, 0.40, y1)
    if shield:                                                                      # a grounded metal 1 strip between the X bus and the plates
        t.r("metal1", -0.60, yx1 + 0.14, x, yx1 + 0.28); t.r("metal1", -0.60, -1.74, -0.30, yx1 + 0.28); t.r("metal1", -0.60, -1.74, 0, -1.34)
    y0 = yp - 0.05; ytop = y0 + max(s["ah"] for s in seats)
    if split:                                                                       # coupling plate as two combs of metal 2 stripes, CP1 and CP2
        i = 0
        while y0 + 0.5 * i + 0.36 <= ytop + 1e-9:
            a = y0 + 0.5 * i
            if i % 2 == 0: t.r("metal2", -0.44, a, x, a + 0.36)
            else: t.r("metal2", 0, a, x + 0.44, a + 0.36)
            i += 1
        t.r("metal2", -0.44, y0, -0.14, ytop); t.r("metal2", x + 0.14, y0, x + 0.44, ytop)
        t.pin("CP1", "metal2", -0.44, y0, -0.14, y0 + 0.40); t.pin("CP2", "metal2", x + 0.14, y0, x + 0.44, y0 + 0.40); cps = "CP1 CP2"
    else:
        t.r("metal2", 0, y0, x, ytop); t.pin("CP", "metal2", 0, y0, 0.40, y0 + 0.40); cps = "CP"
    head, tail = frame(name)
    if hints: tail = ['property MASKHINTS_HVI "' + " ".join(str(round(v * 200)) for v in hints) + '"'] + tail
    ref = [f"* Reference for LVS, generated from table '{name}'. Do not edit by hand.", f".subckt {name} X VB GND {cps} " + " ".join(r["sel"] for r in rows)]
    for r in rows:
        k = r["seat"]; g = "VB" if r["opt"] == "tied" else f"fg{k}"
        ref.append(f"XD{k} X {g} s{k} GND {r['model']} w={r['w']:g} l={r['l']:g}")
        ref.append(f"XS{k} s{k} SEL{k} GND GND sky130_fd_pr__nfet_01v8 w={SW_W:g} l={SW_L:g}")
        if r["opt"] == "diode": ref.append(f"XJ{k} GND {g} sky130_fd_pr__diode_pw2nd_05v5 area={0.45 * 0.45 * 1e12:g} perim={4 * 0.45 * 1e6:g}")
    ref.append(".ends")
    csv = ["seat,id,x_um,oxide,ant_w_um,ant_h_um,option,select"] + [f"{r['seat']},{r['id']},{r['x']},{r['ox']},{r['aw']},{r['ah']},{r['opt']},{r['sel']}" for r in rows]
    return name, "\n".join(head + t.l + tail) + "\n", "\n".join(ref) + "\n", "\n".join(csv) + "\n"


def build_reader2(table, pitch_delta=0.0):
    """Reader 2, analog front end: the node capacitor (nfet, gate on X, source, drain and body on GND) and the precharge
    stacks above it in one n-well. Each stack is one p+ strip with four hvt gates, VDD . g . g . X . g . g . VDD: two parallel
    branches of two pfets in series, the middle nodes left without contact. One gate line per stack (range select).
    Table: {"name": ..., "kind": "reader2", "cap": {"w": 4.3, "l": 4.0}, "pw": 1.0, "stack_gap": 0.27,
            "stacks": [{"pin": "PRENH", "l": 0.15}, {"pin": "PRENL", "l": 1.0}]}"""
    name = table["name"]; cw, cl = float(table["cap"]["w"]), float(table["cap"]["l"]); pw = float(table.get("pw", 1.0))
    sg = float(table.get("stack_gap", 0.27)); t = Tcl()
    # node capacitor
    xe = 0.30 + cl + 0.30
    t.r("ndiff", 0, 0, xe, cw); t.r("poly", 0.30, -0.13, 0.30 + cl, cw + 0.50)
    for x0 in (0.04, xe - 0.21):
        t.r("ndiffc", x0, 0.06, x0 + 0.17, cw - 0.06); t.r("locali", x0, -0.60, x0 + 0.17, cw + 0.02)
    tx = xe + GAP
    t.r("psubdiff", tx, 0, tx + TAP, cw); t.r("psubdiffcont", tx + 0.125, 0.06, tx + 0.295, cw - 0.06)
    t.r("locali", tx + 0.125, -0.60, tx + 0.295, cw + 0.02); t.r("locali", 0.04, -0.60, tx + 0.295, -0.43)
    yb0, yb1 = cw + 0.25, cw + 0.42                                                 # X bar on li, over the gate contacts
    x = 0.47
    while x + 0.17 <= 0.30 + cl - 0.08:
        t.r("polycont", x, yb0, x + 0.17, yb1); x += 0.34
    # precharge stacks
    yd0 = cw + 0.98; yd1 = yd0 + pw; ypb = yd1 + 0.13; yv = ypb + 0.57; x = 0.40; ref = []; pins = []; xmax = 0
    for k, st in enumerate(table["stacks"]):
        L = float(st["l"]); g = [x + 0.30, x + 0.30 + L + 0.21, x + 0.30 + 2 * L + 0.21 + 0.35, x + 0.30 + 3 * L + 0.42 + 0.35]
        xend = g[3] + L + 0.30; xc = g[1] + L + 0.09
        t.r("pdiff", x, yd0, xend, yd1)
        for gx in g: t.r("poly", gx, yd0 - 0.13, gx + L, ypb); t.r("pfethvt", gx, yd0, gx + L, yd1)
        t.r("poly", g[0], ypb, g[3] + L, ypb + 0.36)                                # gate bar and its contact
        t.r("polycont", xc, ypb + 0.11, xc + 0.17, ypb + 0.28); t.r("locali", xc - 0.08, ypb + 0.11, xc + 0.25, ypb + 0.28)
        t.r("viali", xc, ypb + 0.11, xc + 0.17, ypb + 0.28); cx, cy = xc + 0.085, ypb + 0.195
        t.r("metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20); t.pin(st["pin"], "metal1", cx - 0.20, cy - 0.20, cx + 0.20, cy + 0.20)
        for x0 in (x + 0.04, xend - 0.21):                                          # ends -> VDD bar
            t.r("pdiffc", x0, yd0 + 0.06, x0 + 0.17, yd1 - 0.06); t.r("locali", x0, yd0 - 0.02, x0 + 0.17, yv + 0.17)
        t.r("pdiffc", xc, yd0 + 0.06, xc + 0.17, yd1 - 0.06); t.r("locali", xc, yb0, xc + 0.17, yd1 + 0.02)   # middle -> X bar
        p = st["pin"]; m = "sky130_fd_pr__pfet_01v8_hvt"
        for b in (0, 1):
            ref += [f"XP{k}{b}a X {p} m{k}{b} VDD {m} w={pw:g} l={L:g}", f"XP{k}{b}b m{k}{b} {p} VDD VDD {m} w={pw:g} l={L:g}"]
        pins.append(p); xmax = xend; x = xend + sg + pitch_delta
    nx = xmax + GAP                                                                 # well tap
    t.r("nsubdiff", nx, yd0, nx + TAP, yd1); t.r("nsubdiffcont", nx + 0.125, yd0 + 0.06, nx + 0.295, yd1 - 0.06)
    t.r("locali", nx + 0.125, yd0 - 0.02, nx + 0.295, yv + 0.17)
    t.r("nwell", 0.40 - WENC, yd0 - WENC, nx + TAP + WENC, yd1 + WENC)
    t.r("locali", 0.44, yv, nx + 0.295, yv + 0.17)                                  # VDD bar
    xr = max(0.30 + cl, xmax) - 0.30
    t.r("locali", 0.39, yb0, xr + 0.60, yb1)                                        # X bar
    for nm, px, py in (("X", xr + 0.40, (yb0 + yb1) / 2), ("VDD", nx - 0.60, yv + 0.085), ("GND", 2.0, -0.515)):
        t.r("viali", px - 0.085, py - 0.085, px + 0.085, py + 0.085)
        t.r("metal1", px - 0.20, py - 0.20, px + 0.20, py + 0.20); t.pin(nm, "metal1", px - 0.20, py - 0.20, px + 0.20, py + 0.20)
    head, tail = frame(name)
    ref = [f"* Reference for LVS, generated from table '{name}'. Do not edit by hand.", f".subckt {name} X {' '.join(pins)} VDD GND",
           f"XC GND X GND GND sky130_fd_pr__nfet_01v8 w={cw:g} l={cl:g}"] + ref + [".ends"]
    csv = ["seat,id,l_um,pin"] + [f"{k},stack{k},{st['l']},{st['pin']}" for k, st in enumerate(table["stacks"])]
    return name, "\n".join(head + t.l + tail) + "\n", "\n".join(ref) + "\n", "\n".join(csv) + "\n"


